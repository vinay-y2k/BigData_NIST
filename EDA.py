import io
import time
import psycopg2
import yfinance as yf
import pandas as pd
from pathlib import Path
from dotenv import dotenv_values

# Get the path to the directory where this script lives
SCRIPT_DIR = Path(__file__).resolve().parent
env_path = SCRIPT_DIR/".."/ ".env"

config = dotenv_values(env_path)

# Optimized Laptop-Safe DB Config
DB_CONFIG = {
    "dbname": config['DB_NAME'],
    "user": config['DB_USER'],
    "password": config['DB_PASSWORD'],
    "host": "localhost",
    "port": 5432
}

def initialize_database():
    """Drops old entities and creates a clean schema optimized for time-series and vectors."""
    conn = psycopg2.connect(**DB_CONFIG)
    cursor = conn.cursor()
    
    setup_queries = """
    CREATE EXTENSION IF NOT EXISTS vector;
    
    DROP TABLE IF EXISTS market_analysis_cache CASCADE;
    DROP TABLE IF EXISTS price_velocity_ticks CASCADE;
    DROP TABLE IF EXISTS asset_metadata CASCADE;

    CREATE TABLE asset_metadata (
        asset_id SERIAL PRIMARY KEY,
        ticker VARCHAR(12) NOT NULL UNIQUE,
        company_name VARCHAR(255),
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE price_velocity_ticks (
        tick_id BIGSERIAL PRIMARY KEY,
        asset_id INT REFERENCES asset_metadata(asset_id) ON DELETE CASCADE,
        timestamp TIMESTAMP WITH TIME ZONE NOT NULL,
        open_price DECIMAL(18, 4) NOT NULL,
        high_price DECIMAL(18, 4) NOT NULL,
        low_price DECIMAL(18, 4) NOT NULL,
        close_price DECIMAL(18, 4) NOT NULL,
        volume BIGINT NOT NULL,
        price_velocity DECIMAL(12, 6) NOT NULL
    );

    CREATE TABLE market_analysis_cache (
        cache_id BIGSERIAL PRIMARY KEY,
        query_text TEXT NOT NULL,
        semantic_embedding vector(768) NOT NULL,
        structured_sql_fallback TEXT,
        execution_route VARCHAR(50) NOT NULL,
        confidence_score DECIMAL(5, 4) NOT NULL
    );

    CREATE INDEX idx_ticks_asset_timestamp ON price_velocity_ticks(asset_id, timestamp DESC);
    """
    print("Constructing secure NIST-aligned database schema...")
    cursor.execute(setup_queries)
    conn.commit()
    cursor.close()
    conn.close()

def run_laptop_ingestion_pipeline():
    """
    Downloads historical market data, flattens MultiIndex structures,
    transforms metrics on-the-fly, and bulk streams using COPY protocol.
    """
    tickers = [
        "AAPL", "MSFT", "NVDA", "AMZN", "GOOGL", "META", "TSLA", "BRK-B", "JPM", "V",
        "XOM", "CVX", "JNJ", "LLY", "PG", "HD", "COST", "MA", "UNH", "BAC", 
        "DIS", "AVGO", "AMD", "NFLX", "ADBE", "CRM", "INTC", "TXN"
    ]
    # Eliminate any potential array duplicates cleanly
    tickers = list(set(tickers))
    
    conn = psycopg2.connect(**DB_CONFIG)
    cursor = conn.cursor()
    
    # Map and seed Asset Dimensions
    print("Mapping asset dimension tables...")
    asset_map = {}
    for ticker in tickers:
        cursor.execute(
            "INSERT INTO asset_metadata (ticker, company_name) VALUES (%s, %s) ON CONFLICT (ticker) DO UPDATE SET ticker=EXCLUDED.ticker RETURNING asset_id;",
            (ticker, f"{ticker} Corp")
        )
        # Fetchone returns a tuple (asset_id,), grab the index 0 scalar integer
        asset_map[ticker] = cursor.fetchone()[0]
    conn.commit()

    # Initialize high-velocity string memory stream
    buffer = io.StringIO()
    total_rows = 0
    start_time = time.time()
    
    print(f" Extracting daily history for {len(tickers)} assets from Yahoo Finance...")
    for ticker in tickers:
        asset_id = asset_map[ticker]
        
        # Download data isolating one asset at a time
        df = yf.download(ticker, period="max", interval="1d", progress=False)
        if df.empty:
            continue
            
        # FIX: Force-flatten MultiIndex column layouts generated by yfinance
        if isinstance(df.columns, pd.MultiIndex):
            df.columns = df.columns.get_level_values(0)
            
        df = df.reset_index()
        
        # Vectorized transformations via pandas Series accessor methods
        dates = df['Date'].dt.strftime('%Y-%m-%d %H:%M:%S%z').to_numpy()
        opens = df['Open'].to_numpy()
        highs = df['High'].to_numpy()
        lows = df['Low'].to_numpy()
        closes = df['Close'].to_numpy()
        volumes = df['Volume'].to_numpy()
        
        # Sequential write array flight processing
        for idx in range(len(df)):
            price_velocity = float(closes[idx]) - float(opens[idx])
            
            buffer.write(
                f"{asset_id}\t{dates[idx]}\t{float(opens[idx]):.4f}\t"
                f"{float(highs[idx]):.4f}\t{float(lows[idx]):.4f}\t"
                f"{float(closes[idx]):.4f}\t{int(volumes[idx])}\t"
                f"{price_velocity:.6f}\n"
            )
            total_rows += 1

    # Return buffer pointer position window back to position 0 before flight
    buffer.seek(0)
    print(f" Streaming {total_rows:,} records directly into your local container...")
    try:
        cursor.copy_from(
            buffer, 
            'price_velocity_ticks', 
            columns=('asset_id', 'timestamp', 'open_price', 'high_price', 'low_price', 'close_price', 'volume', 'price_velocity')
        )
        conn.commit()
        duration = time.time() - start_time
        print(f"\n✅ Ingestion Pipeline Success!")
        print(f" Loaded {total_rows:,} total rows in {duration:.2f} seconds ({total_rows/duration:.2f} rows/sec).")
    except Exception as e:
        conn.rollback()
        print(f"Ingestion stopped: {e}")
    finally:
        cursor.close()
        conn.close()
        buffer.close()


if __name__ == "__main__":
    initialize_database()
    run_laptop_ingestion_pipeline()
